from __future__ import annotations

import re
from pathlib import Path

from test_docs_validation import (
    ADRS,
    make_repository,
    run_generate,
    run_validate,
    write_work_item,
)


def test_status_generation_is_sorted_deterministic_and_immediately_clean(tmp_path: Path) -> None:
    make_repository(tmp_path)
    first_work_item = tmp_path / "docs" / "work" / "WI-0001-weak-article-router-v1.md"
    first_work_item.write_text(
        first_work_item.read_text(encoding="utf-8").replace("focus: true", "focus: false"),
        encoding="utf-8",
        newline="\n",
    )
    write_work_item(
        tmp_path,
        "WI-0002",
        "dependent-work",
        "Dependent work",
        focus=False,
        owner="beta",
        depends_on=("WI-0001",),
    )
    write_work_item(
        tmp_path,
        "WI-0003",
        "current-focus",
        "Current focus",
        focus=True,
        owner="alpha",
        depends_on=("WI-0002", "WI-0001"),
    )

    generated = run_generate(tmp_path)

    assert generated.returncode == 0
    assert generated.stdout == ""
    assert generated.stderr == ""
    status = (tmp_path / "docs" / "STATUS.md").read_bytes()
    expected = (
        "# Project Status\n\n"
        "<!-- GENERATED by scripts/generate_status.py; DO NOT EDIT. -->\n\n"
        "Focus: [WI-0003](work/WI-0003-current-focus.md)\n\n"
        "## Work Items\n\n"
        "| ID | Title | Status | Owner | Focus | Depends on |\n"
        "|---|---|---|---|---|---|\n"
        "| [WI-0003](work/WI-0003-current-focus.md) | Current focus | active | alpha | "
        "true | WI-0001, WI-0002 |\n"
        "| [WI-0001](work/WI-0001-weak-article-router-v1.md) | Weak Article Router v1 | "
        "active | codex | false | — |\n"
        "| [WI-0002](work/WI-0002-dependent-work.md) | Dependent work | active | beta | "
        "false | WI-0001 |\n\n"
        "## Decisions\n\n"
        "| ID | Title | Status | Supersedes | Superseded by |\n"
        "|---|---|---|---|---|\n"
        + "".join(
            f"| [{adr_id}](decisions/{filename}) | {title} | accepted | — | — |\n"
            for filename, adr_id, title in ADRS
        )
    ).encode("utf-8")
    assert status == expected

    regenerated = run_generate(tmp_path)
    assert regenerated.returncode == 0
    assert (tmp_path / "docs" / "STATUS.md").read_bytes() == status

    checked = run_generate(tmp_path, "--check")
    assert checked.returncode == 0
    assert checked.stdout == ""
    assert checked.stderr == ""
    assert (tmp_path / "docs" / "STATUS.md").read_bytes() == status


def test_check_detects_byte_drift_without_writing_and_validator_reports_doc009(
    tmp_path: Path,
) -> None:
    make_repository(tmp_path)
    generated = run_generate(tmp_path)
    assert generated.returncode == 0
    status_path = tmp_path / "docs" / "STATUS.md"
    drifted = status_path.read_bytes() + b"manual edit\n"
    status_path.write_bytes(drifted)

    checked = run_generate(tmp_path, "--check")

    assert checked.returncode == 1
    assert "DOC009_STATUS_DRIFT" in checked.stdout
    assert checked.stderr == ""
    assert status_path.read_bytes() == drifted

    validated = run_validate(tmp_path)
    assert validated.returncode == 1
    assert any(
        line.startswith("DOC009_STATUS_DRIFT docs/STATUS.md:")
        for line in validated.stdout.splitlines()
    )


def test_invalid_metadata_prevents_status_write(tmp_path: Path) -> None:
    make_repository(tmp_path)
    work_item = tmp_path / "docs" / "work" / "WI-0001-weak-article-router-v1.md"
    work_item.write_text(
        work_item.read_text(encoding="utf-8").replace("focus: true", "focus: false"),
        encoding="utf-8",
        newline="\n",
    )

    generated = run_generate(tmp_path)

    assert generated.returncode == 1
    assert "DOC004_FOCUS_CARDINALITY" in generated.stdout
    assert generated.stderr == ""
    assert not (tmp_path / "docs" / "STATUS.md").exists()


def test_owner_pipe_is_escaped_into_a_six_column_status_row(tmp_path: Path) -> None:
    make_repository(tmp_path)
    work_item = tmp_path / "docs" / "work" / "WI-0001-weak-article-router-v1.md"
    work_item.write_text(
        work_item.read_text(encoding="utf-8").replace("owner: codex", "owner: alpha|beta"),
        encoding="utf-8",
        newline="\n",
    )

    generated = run_generate(tmp_path)

    assert generated.returncode == 0
    assert generated.stdout == ""
    assert generated.stderr == ""
    status_path = tmp_path / "docs" / "STATUS.md"
    row = next(
        line
        for line in status_path.read_text(encoding="utf-8").splitlines()
        if line.startswith("| [WI-0001]")
    )
    assert "alpha\\|beta" in row
    assert len(re.split(r"(?<!\\)\|", row)[1:-1]) == 6

    checked = run_generate(tmp_path, "--check")
    assert checked.returncode == 0
    assert checked.stdout == ""
    assert checked.stderr == ""
